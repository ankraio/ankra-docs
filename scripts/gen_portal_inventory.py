#!/usr/bin/env python3
"""Write scripts/portal-inventory.json: the routes the Ankra portal serves and
the strings it can show as a label, read from the portal's source.

scripts/check_portal_labels.py checks every bold menu path and every /next
address a page states against this file. The portal's repository
(ankraio/ankra-frontend) is private, so Docs CI cannot read it; the inventory
is vendored here and regenerated by hand, like the role matrix
(scripts/gen_role_matrix.py):

    git -C ../ankra-frontend fetch origin
    python3 scripts/gen_portal_inventory.py --frontend-repo ../ankra-frontend
    python3 scripts/check_portal_labels.py

--ref picks the portal revision (default origin/main). The source is read
from that commit with `git archive`, never from the checked-out tree, so a
local branch or an uncommitted edit in the portal checkout cannot leak into
the inventory. Needs git and nothing else.

What it records:

  routes  every page under src/pages (Next.js Pages Router, served under the
          basePath in next.config.ts), as the address a reader types:
          /next/clusters/[id]/settings. src/pages/api, _app and _document
          are not pages. [id] is one dynamic segment, [...x] one or more,
          [[...x]] zero or more.
  labels  every string literal, template-literal text and JSX text in
          src/**/*.ts(x), tests excluded, that can be a label: at most 50
          characters and 5 words, at least one letter, not starting in lower
          case (identifiers, ids, enum values, class lists and sentence
          fragments do), not a sentence, and not code-shaped (paths, URLs,
          markup, interpolation, CONSTANT_CASE). The filter only drops strings
          no menu shows; it keeps the file small enough to review and diff.

The file records the commit and its date, and the check prints both when it
fails, because a page that documents a label newer than the inventory fails
until someone regenerates it.

`--self-test` runs the extractor's own assertions.
"""

from __future__ import annotations

import argparse
import io
import json
import os
import re
import subprocess
import sys
import tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "scripts", "portal-inventory.json")
REPOSITORY = "ankraio/ankra-frontend"
SOURCE_DIRECTORY = "src"
PAGES_DIRECTORY = "src/pages/"
SOURCE_SUFFIXES = (".ts", ".tsx")
PAGE_SUFFIXES = (".tsx", ".ts", ".jsx", ".js")
NOT_PAGES = {"_app", "_document", "_error"}
TEST_FILE = re.compile(r"(?:\.(?:test|spec|stories)\.[jt]sx?$)|(?:^|/)__(?:tests|mocks)__/")
MAX_LABEL = 50
MAX_WORDS = 5

STRING = re.compile(r"""'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*\"""")
CODE_TOKEN = re.compile(r"//|/\*|['\"`{}/]")
REGEX_AFTER = set("(,=:[!&|?{};+-*%~^<>")
# JSX text: what stands between a tag's > (or an expression's }) and the next tag or expression.
JSX_TEXT = re.compile(r"[>}]([^<>{}\x01]+)(?=[<{])")
MESSAGE_PLACEHOLDER = re.compile(r"\{[A-Za-z_][A-Za-z0-9_]*\}")
LOCALES_FILE = "src/lib/i18n/locales.ts"
ESCAPE = re.compile(r"\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|.)", re.S)
ENTITY = {"&amp;": "&", "&apos;": "'", "&quot;": '"', "&nbsp;": " ", "&lt;": "<", "&gt;": ">", "&rsquo;": "\u2019", "&hellip;": "\u2026"}


def unescape(body: str) -> str:
    def replace(match: re.Match) -> str:
        code = match.group(1)
        if code.startswith("u{"):
            return chr(int(code[2:-1], 16))
        if code[0] == "u" and len(code) == 5:
            return chr(int(code[1:], 16))
        if code[0] == "x" and len(code) == 3:
            return chr(int(code[1:], 16))
        return {"n": "\n", "t": "\t", "r": "\r"}.get(code, code)

    return ESCAPE.sub(replace, body)


def previous_significant(text: str, index: int) -> str:
    """The last non-space character before index, or the word before it when it is a keyword."""
    k = index - 1
    while k >= 0 and text[k] in " \t\r\n":
        k -= 1
    if k < 0:
        return ""
    if text[k].isalnum() or text[k] in "_$":
        start = k
        while start > 0 and (text[start - 1].isalnum() or text[start - 1] in "_$"):
            start -= 1
        return text[start : k + 1]
    return text[k]


def lex(source: str) -> tuple[str, list[tuple[str, int]]]:
    """(masked, strings): the source with comments dropped and every string,
    template literal and regular expression replaced by \\x01, and each
    literal's text with the offset of its \\x01 in masked.

    An apostrophe or quote right after a letter or digit is text, not a
    string: JSX text such as Don't would otherwise open a literal."""
    strings: list[tuple[str, int]] = []
    out: list[str] = []
    size = 0

    def emit(text: str) -> None:
        nonlocal size
        out.append(text)
        size += len(text)

    def scan(i: int, in_expression: bool) -> int:
        depth = 0
        n = len(source)
        while True:
            match = CODE_TOKEN.search(source, i)
            if not match:
                emit(source[i:])
                return n
            j = match.start()
            token = match.group()
            emit(source[i:j])
            if token == "//":
                end = source.find("\n", j)
                i = n if end < 0 else end
            elif token == "/*":
                end = source.find("*/", j + 2)
                i = n if end < 0 else end + 2
            elif token in "'\"":
                literal = STRING.match(source, j)
                if (j > 0 and source[j - 1].isalnum()) or not literal:
                    emit(token)
                    i = j + 1
                else:
                    strings.append((unescape(literal.group()[1:-1]), size))
                    emit("\x01")
                    i = literal.end()
            elif token == "`":
                offset = size
                emit("\x01")
                i = template(j + 1, offset)
            elif token == "{":
                depth += 1
                emit(token)
                i = j + 1
            elif token == "}":
                if in_expression and depth == 0:
                    return j + 1
                depth -= 1
                emit(token)
                i = j + 1
            else:  # a lone /: a regular-expression literal or a division
                before = previous_significant(source, j)
                end = regex_end(j) if (before == "" or before in REGEX_AFTER or before in ("return", "typeof")) else -1
                if end < 0:
                    emit(token)
                    i = j + 1
                else:
                    emit("\x01")
                    i = end

    def regex_end(j: int) -> int:
        k = j + 1
        in_class = False
        n = len(source)
        while k < n and source[k] != "\n":
            c = source[k]
            if c == "\\":
                k += 2
                continue
            if c == "[":
                in_class = True
            elif c == "]":
                in_class = False
            elif c == "/" and not in_class:
                k += 1
                while k < n and source[k].isalpha():
                    k += 1
                return k
            k += 1
        return -1

    def template(i: int, offset: int) -> int:
        segment: list[str] = []
        n = len(source)
        while i < n:
            c = source[i]
            if c == "\\":
                segment.append(unescape(source[i : i + 2]))
                i += 2
            elif c == "`":
                strings.append(("".join(segment), offset))
                return i + 1
            elif c == "$" and source.startswith("${", i):
                strings.append(("".join(segment), offset))
                segment = []
                emit(" ")
                i = scan(i + 2, True)
                emit(" ")
            else:
                segment.append(c)
                i += 1
        strings.append(("".join(segment), offset))
        return n

    scan(0, False)
    return "".join(out), strings


def translation_blocks(masked: str, locales: list[str]) -> list[tuple[int, int]]:
    """The spans of the objects that hold another locale's text: `sv: { ... }` in a
    defineMessages call, `export const sv: Catalogue = { ... }` in a catalogue."""
    if not locales:
        return []
    opening = re.compile(r"\b(?:%s)\b\s*(?::\s*[A-Za-z_][\w.]*\s*=|:)\s*\{" % "|".join(map(re.escape, locales)))
    blocks = []
    for match in opening.finditer(masked):
        start = match.end() - 1
        depth = 0
        for index in range(start, len(masked)):
            if masked[index] == "{":
                depth += 1
            elif masked[index] == "}":
                depth -= 1
                if depth == 0:
                    blocks.append((start, index))
                    break
    return blocks


def decode_entities(text: str) -> str:
    text = re.sub(r"&#(\d+);", lambda m: chr(int(m.group(1))), text)
    text = re.sub(r"&#x([0-9a-fA-F]+);", lambda m: chr(int(m.group(1), 16)), text)
    for entity, character in ENTITY.items():
        text = text.replace(entity, character)
    return text


def texts(source: str, jsx: bool, locales: list[str] | None = None) -> list[str]:
    """Every string literal, template-literal text and (in .tsx) JSX text, split at
    message placeholders ({count}). A value inside another locale's block is a
    translation, not English, and is left out; its key is the English text and stays."""
    masked, strings = lex(source)
    blocks = translation_blocks(masked, locales or [])
    found = []
    for text, offset in strings:
        if any(start < offset < end for start, end in blocks) and not masked[offset + 1 :].lstrip().startswith(":"):
            continue
        found.extend(MESSAGE_PLACEHOLDER.split(text))
    if jsx:
        found.extend(decode_entities(match.group(1)) for match in JSX_TEXT.finditer(masked))
    return found


def collapse(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u00a0", " ")).strip()


def label_like(text: str) -> bool:
    """Whether a source string can be a label a menu, tab, button or heading shows: short, not a
    sentence, and not code. A label starts with a capital, a digit or a symbol; identifiers, ids,
    enum values, class lists and sentence fragments ("now", "clusters") start in lower case."""
    if not text or len(text) > MAX_LABEL or not re.search(r"[A-Za-z]", text):
        return False
    first = text[0]
    if not (first.isupper() or first.isdigit() or first == "+" or (not first.isascii() and not first.islower())):
        return False  # lower case, or code punctuation such as ( ! , "
    words = text.split(" ")
    if len(words) > MAX_WORDS or (len(words) > 2 and text[-1] in ".?!"):
        return False
    if re.search(r"[{}<>;=$\\`|\x00-\x1f\x01]", text) or "://" in text:
        return False  # markup, interpolation, code, a URL
    if text.startswith(("/", "./", "../", "#", "@", ".", "-", "_", "*")):
        return False  # a path, an anchor, a package, a flag
    if re.fullmatch(r"[A-Z0-9]+(?:_[A-Z0-9]+)+", text):
        return False  # CONSTANT_CASE
    return True


def route_of(path: str) -> str | None:
    """The address of a page file under src/pages, without the basePath, or None."""
    relative = path[len(PAGES_DIRECTORY) :]
    stem, suffix = os.path.splitext(relative)
    if suffix not in PAGE_SUFFIXES or TEST_FILE.search(relative):
        return None
    if stem.split("/")[0] == "api" or os.path.basename(stem) in NOT_PAGES:
        return None
    if stem == "index":
        return "/"
    if stem.endswith("/index"):
        stem = stem[: -len("/index")]
    return "/" + stem


def read_tree(frontend_repo: str, ref: str) -> tuple[str, str, dict[str, str]]:
    def git(*args: str) -> bytes:
        return subprocess.run(["git", "-C", frontend_repo, *args], check=True, capture_output=True).stdout

    commit = git("rev-parse", "--verify", f"{ref}^{{commit}}").decode().strip()
    date = git("show", "-s", "--format=%cI", commit).decode().strip()
    archive = git("archive", "--format=tar", commit, SOURCE_DIRECTORY, "next.config.ts")
    files: dict[str, str] = {}
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            if member.isfile():
                handle = tar.extractfile(member)
                if handle is not None:
                    files[member.name] = handle.read().decode("utf-8", errors="replace")
    return commit, date, files


def build(files: dict[str, str]) -> tuple[str, list[str], list[str], dict]:
    config = files.get("next.config.ts", "")
    base = re.search(r"""\bbasePath\s*:\s*['"]([^'"]+)['"]""", config)
    if not base:
        raise SystemExit("next.config.ts sets no basePath; the portal's addresses cannot be derived")
    base_path = base.group(1).rstrip("/")
    # The portal's languages; every one but English is a translation (src/lib/i18n/locales.ts).
    declared = re.search(r"\bLOCALES\s*=\s*\[([^\]]*)\]", files.get(LOCALES_FILE, ""))
    locales = [code for code in re.findall(r"""['"]([a-z]{2,3}(?:-[A-Za-z]+)?)['"]""", declared.group(1)) if code != "en"] if declared else []
    routes = set()
    candidates: set[str] = set()
    sources = 0
    for path, source in files.items():
        if path.startswith(PAGES_DIRECTORY):
            route = route_of(path)
            if route is not None:
                routes.add(base_path if route == "/" else base_path + route)
        if not path.startswith(SOURCE_DIRECTORY + "/") or not path.endswith(SOURCE_SUFFIXES) or TEST_FILE.search(path):
            continue
        sources += 1
        for text in texts(source, path.endswith(".tsx"), locales):
            candidates.add(collapse(text))
    labels = sorted(text for text in candidates if label_like(text))
    stats = {"source_files": sources, "strings_seen": len(candidates), "labels_kept": len(labels), "locales_left_out": locales}
    return base_path, sorted(routes), labels, stats


def render(commit: str, date: str, ref: str, base_path: str, routes: list[str], labels: list[str]) -> str:
    head = {
        "about": (
            "Generated by scripts/gen_portal_inventory.py from the portal's source; do not edit by hand. "
            "Regenerate: python3 scripts/gen_portal_inventory.py --frontend-repo <ankra-frontend checkout>"
        ),
        "repository": REPOSITORY,
        "ref": ref,
        "commit": commit,
        "commit_date": date,
        "base_path": base_path,
    }
    lines = ["{"]
    for key, value in head.items():
        lines.append(f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)},")
    for key, values in (("routes", routes), ("labels", labels)):
        lines.append(f"  {json.dumps(key)}: [")
        lines.extend(f"    {json.dumps(value, ensure_ascii=False)}," for value in values)
        if values:
            lines[-1] = lines[-1].rstrip(",")
        lines.append("  ]," if key == "routes" else "  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def self_test() -> None:
    source = "\n".join(
        [
            "// a comment with 'Not a label'",
            "const tabs = [{ id: 'general', label: 'General' }, { label: \"Danger zone\" }]",
            "const t = `Delete ${name} now`",
            "const r = /it's/g.test(x) ? a / b : c",
            "export function X() {",
            "  return (",
            "    <Tabs title={'Cluster settings'} className=\"flex items-center gap-2\">",
            "      <Button>",
            "        Create cluster",
            "      </Button>",
            "      <p>Don't delete {count} clusters &amp; stacks</p>",
            "    </Tabs>",
            "  )",
            "}",
            "export const text = defineMessages(['Open {name} (new tab)', 'Plan and billing'], {",
            "  sv: { 'Plan and billing': 'Plan och fakturering', 'Open {name} (new tab)': 'Öppna {name} (ny flik)' },",
            "})",
            "export const sv: Catalogue = { Home: 'Hem', 'Your account': 'Ditt konto' }",
        ]
    )
    found = {collapse(text) for text in texts(source, jsx=True, locales=["sv"])}
    for wanted in ["General", "Danger zone", "Delete", "now", "Cluster settings", "Create cluster", "Don't delete", "clusters & stacks"]:
        assert wanted in found, (wanted, sorted(found))
    assert "Not a label" not in found, "comments are not read"
    assert not any("it's" in text for text in found), "a regular expression is not a string"
    assert {"Open", "(new tab)", "Plan and billing", "Your account"} <= found, "message keys are English, split at {placeholders}"
    assert not {"Plan och fakturering", "Hem", "Ditt konto", "Öppna"} & found, "translations are left out"
    kept = {text for text in found if label_like(text)}
    assert "general" not in kept and "flex items-center gap-2" not in kept, sorted(kept)
    assert {"General", "Danger zone", "Create cluster", "Cluster settings"} <= kept, sorted(kept)
    for code in ["clusterId", "MAX_RETRIES", "cluster-id", "/clusters/[id]", "https://x.io", "${id}", "else", "now"]:
        assert not label_like(code), code
    for sentence in ["Install Trivy Operator to start scanning this cluster's workloads.", "Is the agent running?"]:
        assert not label_like(sentence), sentence
    for label in ["AI", "Settings", "CI/CD", "Source control & AI review", "Add-on", "GitHub", "DigitalOcean", "ConfigMap", "+ Add"]:
        assert label_like(label), label
    assert route_of("src/pages/index.tsx") == "/"
    assert route_of("src/pages/clusters/[id]/settings/index.tsx") == "/clusters/[id]/settings"
    assert route_of("src/pages/clusters/[id]/kubernetes/[...resource].tsx") == "/clusters/[id]/kubernetes/[...resource]"
    assert route_of("src/pages/api/account/billing.ts") is None
    assert route_of("src/pages/_app.tsx") is None
    assert route_of("src/pages/clusters/index.test.tsx") is None
    base, routes, labels, _ = build(
        {
            "next.config.ts": "const c = { basePath: '/next' }",
            "src/pages/index.tsx": "export default () => <h1>Home</h1>",
            "src/pages/clusters/[id].tsx": "const x = 'Overview'",
            "src/features/a.test.tsx": "const y = 'Only in a test'",
            "src/lib/i18n/locales.ts": "export const LOCALES = ['en', 'sv'] as const",
            "src/lib/i18n/catalogues/sv.ts": "export const sv: Catalogue = { 'Overview': 'Översikt' }",
        }
    )
    assert base == "/next" and routes == ["/next", "/next/clusters/[id]"], routes
    assert labels == ["Home", "Overview"], labels
    for junk in ["(CVSS", ", as of", "!open)) const", '"Registry storage:']:
        assert not label_like(junk), junk
    print("portal inventory self-test: ok")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--frontend-repo", type=str, help="an ankra-frontend checkout (only its git objects are read)")
    parser.add_argument("--ref", default="origin/main", help="the portal revision to read (default origin/main)")
    parser.add_argument("--output", default=OUTPUT, help="where to write the inventory (default scripts/portal-inventory.json)")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return 0
    if not args.frontend_repo:
        parser.error("--frontend-repo is required")
    commit, date, files = read_tree(args.frontend_repo, args.ref)
    base_path, routes, labels, stats = build(files)
    text = render(commit, date, args.ref, base_path, routes, labels)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(text)
    size = len(text.encode("utf-8"))
    output = os.path.abspath(args.output)
    shown = os.path.relpath(output, ROOT) if output.startswith(ROOT + os.sep) else output
    print(
        f"{shown}: {len(routes)} routes and {len(labels)} labels "
        f"({stats['strings_seen']} distinct strings in {stats['source_files']} source files) "
        f"from {REPOSITORY} {commit[:12]} ({date}), {size / 1024:.0f} KB"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
