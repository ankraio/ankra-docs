#!/usr/bin/env node
// The parity matrix on reference/flow-parity.mdx is generated from scripts/flow_parity.json and checked here, so a verb
// that is renamed or removed fails the docs build rather than staying documented:
//   - every CLI command must be a heading on the generated reference/cli pages, and every flag must be in its section;
//   - every MCP tool must be listed on platform/mcp-tools.mdx;
//   - every gap must give a reason;
//   - the table on the page must be what this script generates.
// Runs in the image build (Dockerfile), which is the docs' Ankra pipeline. Dependency-free for that reason.
//
// The UI column and the MCP column's source of truth live in private repositories the build cannot read. Pass checkouts
// to check those too, when you edit the matrix:
//   node scripts/check_flow_parity.mjs --frontend ../ankra-frontend --cluster ../cluster
//   node scripts/check_flow_parity.mjs --write          rewrites the table on the page

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const OPEN = '{/* flow-parity:start - generated by scripts/check_flow_parity.mjs, do not edit by hand */}'
const CLOSE = '{/* flow-parity:end */}'

/** Every CLI command the generated reference documents, each with the text of its section. */
export function parseCliReference(pages) {
  const commands = new Map()
  for (const text of pages) {
    const sections = text.split(/^## (?=ankra( |$))/m)
    for (const section of sections.slice(1)) {
      const newline = section.indexOf('\n')
      commands.set(section.slice(0, newline === -1 ? undefined : newline).trim(), section)
    }
  }
  return commands
}

/** Every MCP tool name in the first column of the tool reference's tables. */
export function parseMcpTools(text) {
  return new Set([...text.matchAll(/^\| `([a-z0-9_]+)` \|/gm)].map((match) => match[1]))
}

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const documentsFlag = (section, flag) =>
  section !== undefined && new RegExp(`(^|[^A-Za-z0-9-])${escapeRegExp(flag)}(?![A-Za-z0-9-])`).test(section)

const cellProblems = (where, cell, surface) => {
  if (!cell || typeof cell !== 'object') return [`${where}: no ${surface} cell`]
  if ('gap' in cell) return cell.gap?.trim() ? [] : [`${where}: a gap needs its reason`]
  return []
}

/** What is wrong with the matrix against the references it names; empty when it holds. */
export function findProblems(matrix, cliCommands, mcpTools) {
  const problems = []
  for (const { step, ui, cli, mcp } of matrix.steps) {
    problems.push(...cellProblems(`${step} (UI)`, ui, 'UI'))
    problems.push(...cellProblems(`${step} (CLI)`, cli, 'CLI'))
    problems.push(...cellProblems(`${step} (MCP)`, mcp, 'MCP'))
    if (ui && !('gap' in ui) && !(ui.page && ui.action)) problems.push(`${step} (UI): needs a page and an action`)
    if (cli && !('gap' in cli)) {
      if (!cli.commands?.length) problems.push(`${step} (CLI): names no command`)
      for (const command of cli.commands ?? []) {
        if (!cliCommands.has(command)) problems.push(`${step} (CLI): "${command}" is not in reference/cli`)
      }
      for (const [command, flags] of Object.entries(cli.flags ?? {})) {
        for (const flag of flags) {
          if (!documentsFlag(cliCommands.get(command), flag)) problems.push(`${step} (CLI): "${command}" has no ${flag}`)
        }
      }
    }
    if (mcp && !('gap' in mcp)) {
      if (!mcp.tools?.length) problems.push(`${step} (MCP): names no tool`)
      for (const tool of mcp.tools ?? []) {
        if (!mcpTools.has(tool)) problems.push(`${step} (MCP): "${tool}" is not on platform/mcp-tools.mdx`)
      }
    }
  }
  return problems
}

const code = (text) => `\`${text}\``
const words = (cell) => {
  if ('gap' in cell) return `**Gap.** ${cell.gap}`
  const named = cell.commands
    ? cell.commands.map((command) => code([command, ...(cell.flags?.[command] ?? [])].join(' ')))
    : cell.tools
      ? cell.tools.map(code)
      : [`${code(cell.page)} - ${cell.action}`]
  return [named.join(', '), cell.note].filter(Boolean).join('. ')
}

/** The table on the page. A step's own note goes in the first column. */
export function renderTable(matrix) {
  const rows = matrix.steps.map(
    ({ step, ui, cli, mcp, note }) =>
      `| **${step}**${note ? `<br />${note}` : ''} | ${words(ui)} | ${words(cli)} | ${words(mcp)} |`,
  )
  return ['| Step | UI | CLI | MCP |', '| --- | --- | --- | --- |', ...rows].join('\n')
}

export function withTable(page, table) {
  const start = page.indexOf(OPEN)
  const end = page.indexOf(CLOSE)
  if (start === -1 || end === -1) throw new Error('reference/flow-parity.mdx lost its flow-parity markers')
  return `${page.slice(0, start)}${OPEN}\n\n${table}\n\n${page.slice(end)}`
}

/** The UI pages the matrix names that the frontend checkout does not have. */
export function missingFrontendPages(matrix, frontendRoot) {
  return matrix.steps.flatMap(({ step, ui }) => {
    if (!ui || 'gap' in ui) return []
    const base = join(frontendRoot, 'src/pages', ui.page)
    return existsSync(`${base}.tsx`) || existsSync(join(base, 'index.tsx')) ? [] : [`${step} (UI): no page ${ui.page}`]
  })
}

/** The MCP tools the matrix names that the cluster checkout's tool catalog never mentions. */
export function missingCatalogTools(matrix, clusterRoot) {
  const data = join(clusterRoot, 'go/internal/agentictools/testdata')
  const catalog = ['tool_catalog_goldens.json', 'go_tool_catalog_supplement.json']
    .map((file) => readFileSync(join(data, file), 'utf8'))
    .join('\n')
  return matrix.steps.flatMap(({ step, mcp }) =>
    (mcp?.tools ?? []).filter((tool) => !catalog.includes(`"name": "${tool}"`)).map((tool) => `${step} (MCP): no tool ${tool} in the catalog`),
  )
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..')
  const argument = (name) => {
    const index = process.argv.indexOf(name)
    return index === -1 ? undefined : process.argv[index + 1]
  }
  const matrix = JSON.parse(readFileSync(join(root, 'scripts/flow_parity.json'), 'utf8'))
  const cliDirectory = join(root, 'reference/cli')
  const cliPages = readdirSync(cliDirectory)
    .filter((file) => file.endsWith('.mdx'))
    .map((file) => readFileSync(join(cliDirectory, file), 'utf8'))
  const problems = findProblems(
    matrix,
    parseCliReference(cliPages),
    parseMcpTools(readFileSync(join(root, 'platform/mcp-tools.mdx'), 'utf8')),
  )
  if (argument('--frontend')) problems.push(...missingFrontendPages(matrix, argument('--frontend')))
  if (argument('--cluster')) problems.push(...missingCatalogTools(matrix, argument('--cluster')))
  const pagePath = join(root, 'reference/flow-parity.mdx')
  const page = readFileSync(pagePath, 'utf8')
  const generated = withTable(page, renderTable(matrix))
  if (process.argv.includes('--write')) writeFileSync(pagePath, generated)
  else if (generated !== page) problems.push('reference/flow-parity.mdx is out of date: run node scripts/check_flow_parity.mjs --write')
  if (problems.length) {
    console.error(`Flow parity matrix is wrong:\n  ${problems.join('\n  ')}`)
    process.exit(1)
  }
  console.log(`Flow parity matrix holds: ${matrix.steps.length} steps.`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
