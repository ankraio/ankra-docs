#!/usr/bin/env python3
"""Rewrite the CLI group in docs.json navigation to match reference/cli/*.mdx.

reference/cli is generated by tools/gendocs in ankra-cli, and its docs-sync
workflow runs this script after regenerating so a release that adds or drops
a command family keeps scripts/check_nav.py green without a hand edit. The
group lists reference/cli/index first, then every other page alphabetically.
"""

import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = "reference/cli/"
INDEX = PREFIX + "index"


def find_cli_pages(node):
    """Return the pages list that holds reference/cli/index, or None."""
    if isinstance(node, dict):
        pages = node.get("pages")
        if isinstance(pages, list) and INDEX in pages:
            return pages
        for value in node.values():
            found = find_cli_pages(value)
            if found is not None:
                return found
    elif isinstance(node, list):
        for item in node:
            found = find_cli_pages(item)
            if found is not None:
                return found
    return None


def main() -> int:
    path = os.path.join(ROOT, "docs.json")
    with open(path) as f:
        cfg = json.load(f)

    pages = find_cli_pages(cfg["navigation"])
    if pages is None:
        print(f"ERROR: no navigation group in docs.json lists {INDEX}")
        return 1
    if any(not (isinstance(p, str) and p.startswith(PREFIX)) for p in pages):
        print("ERROR: the CLI navigation group holds entries outside reference/cli; edit it by hand")
        return 1

    on_disk = sorted(
        PREFIX + os.path.basename(f)[: -len(".mdx")]
        for f in glob.glob(os.path.join(ROOT, PREFIX, "*.mdx"))
    )
    want = [INDEX] + [p for p in on_disk if p != INDEX]

    added = sorted(set(want) - set(pages))
    removed = sorted(set(pages) - set(want))
    if pages == want:
        print("CLI navigation already matches reference/cli.")
        return 0

    pages[:] = want
    with open(path, "w") as f:
        f.write(json.dumps(cfg, indent=4, ensure_ascii=False) + "\n")
    for p in added:
        print(f"added   {p}")
    for p in removed:
        print(f"removed {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
